#!/bin/bash
set -e

case "$(pwd -P)" in
    */AtomVM/src/platforms/esp32/build)
        ;;
    *)
        echo "Error: Run this script from a directory ending in AtomVM/src/platforms/esp32/build." >&2
        exit 1
        ;;
esac

IDF_TARGET="$(sed -n 's/^CONFIG_IDF_TARGET="\([^"]*\)"/\1/p' ../sdkconfig)"
if [[ -z "$IDF_TARGET" ]]; then
    echo "Error: CONFIG_IDF_TARGET not found in ../sdkconfig. Make sure you have run 'idf.py set-target' and built AtomVM before running this script." >&2
    exit 1
fi

ZENOH_PICO_SOURCE_DIR="$(sed -n 's/^# Install script for directory: //p' esp-idf/zenoh_pico_component/zenoh-pico/cmake_install.cmake)"
ZENOH_PICO_VERSION="$(git -C "$ZENOH_PICO_SOURCE_DIR" describe --tags --always --dirty)"
ZENOH_PICO_COMMIT="$(git -C "$ZENOH_PICO_SOURCE_DIR" rev-parse --short=8 HEAD)"

ARTIFACT_DIR="zenohex_pico_atomvm_${IDF_TARGET}_artifact_zenoh-pico-${ZENOH_PICO_VERSION}-${ZENOH_PICO_COMMIT}"
ZIP_FILE="${ARTIFACT_DIR}.zip"

test -d "$ARTIFACT_DIR" && rm -r -- "$ARTIFACT_DIR"
mkdir "$ARTIFACT_DIR"
mkdir "$ARTIFACT_DIR/avm_deps"

cp flash_args "$ARTIFACT_DIR/"
sed \
    -e 's|bootloader/bootloader.bin|bootloader.bin|' \
    -e 's|partition_table/partition-table.bin|partition-table.bin|' \
    -e 's|../../../../build/libs/esp32boot/esp32boot.avm|esp32boot.avm|' \
    "$ARTIFACT_DIR/flash_args" > "$ARTIFACT_DIR/flash_args.tmp"
mv "$ARTIFACT_DIR/flash_args.tmp" "$ARTIFACT_DIR/flash_args"

cp bootloader/bootloader.bin                      "$ARTIFACT_DIR/"
cp atomvm-esp32.bin                               "$ARTIFACT_DIR/"
cp partition_table/partition-table.bin            "$ARTIFACT_DIR/"
cp ../../../../build/libs/esp32boot/esp32boot.avm "$ARTIFACT_DIR/"

cp ../../../../build/libs/atomvmlib.avm             "$ARTIFACT_DIR/avm_deps/"
cp ../../../../build/libs/eavmlib/src/eavmlib.avm   "$ARTIFACT_DIR/avm_deps/"
cp ../../../../build/libs/estdlib/src/estdlib.avm   "$ARTIFACT_DIR/avm_deps/"
cp ../../../../build/libs/exavmlib/lib/exavmlib.avm "$ARTIFACT_DIR/avm_deps/"

cat > "$ARTIFACT_DIR/README.md" <<EOF
# Usage

The \`flash_args\` file tells esptool which files to write and where.

The following files are flashed to the target device:

- \`bootloader.bin\`
- \`atomvm-esp32.bin\`
- \`partition-table.bin\`
- \`esp32boot.avm\`

The \`avm_deps/\` directory contains dependencies for the AVM generated by your Elixir AtomVM project.

- \`avm_deps/\`

## How to flash

\`\`\`bash
cd "$ARTIFACT_DIR"
source "\$HOME/.espressif/tools/activate_idf_v5.5.5.sh"
python -m esptool --chip "$IDF_TARGET" -b 460800 --before default_reset --after hard_reset write_flash "@flash_args"
\`\`\`

## How to use avm_deps

Copy \`avm_deps/\` into the root of your Elixir AtomVM project, which must use [exatomvm](https://github.com/atomvm/exatomvm).
EOF

rm -f -- "$ZIP_FILE"
zip -r "$ZIP_FILE" "$ARTIFACT_DIR"
rm -r -- "$ARTIFACT_DIR"
